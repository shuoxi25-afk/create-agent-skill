'use strict';

const fs = require('node:fs');
const path = require('node:path');
const YAML = require('yaml');
const { metadataErrors, parseSkill } = require('./validate');

const templatesRoot = path.join(__dirname, '../templates');
const targets = {
  generic: { label: 'Any Agent Skills-compatible host', directory: null, prefix: '' },
  claude: { label: 'Claude Code', directory: '.claude/skills', prefix: '/' },
  cursor: { label: 'Cursor', directory: '.cursor/skills', prefix: '/' },
  codex: { label: 'Codex', directory: '.agents/skills', prefix: '$' },
};
const templates = {
  basic: { description: null },
  'meeting-notes': {
    description: 'Turn supplied meeting notes or transcripts into decisions, action items with owners and deadlines, and open questions. Use for meeting summaries; mark missing facts as unconfirmed.',
  },
};

function inputError(message) {
  const error = new Error(message);
  error.exitCode = 2;
  throw error;
}

function render(text, variables) {
  return text.replace(/\{\{([A-Z][A-Z0-9_]*)\}\}/g, (match, name) => {
    if (!(name in variables)) throw new Error(`Unknown template variable: ${name}`);
    return variables[name];
  });
}

function installGuide(name, title, target, templateName) {
  const selected = targets[target];
  const invocation = selected.prefix ? `${selected.prefix}${name}` : `Use the ${name} skill in this folder`;
  const trial = templateName === 'meeting-notes'
    ? `${invocation}: summarize the raw meeting notes in references/example.md using assets/meeting-report.md. Treat the expected output as a reference, not as input facts.`
    : `${invocation}: apply the instructions to the following material, then report the result and any missing information. [Paste your task material here.]`;
  return `# ${title}

Generated by [create-agent-skill](https://github.com/shuoxi25-afk/create-agent-skill).

## Install in a project

Selected host: ${selected.label}.
Keep the entire \`${name}\` folder together. Place it under the project directory below.
If it is already there, no copying is needed. A custom --dir only chooses the output location.

| Host | Project location | Invoke |
| --- | --- | --- |
| Claude Code | \`.claude/skills/${name}/\` | \`/${name}\` |
| Cursor | \`.cursor/skills/${name}/\` | \`/${name}\` |
| Codex | \`.agents/skills/${name}/\` | \`$${name}\` |

Open that project in the host and select the skill. If it is not visible, check the folder and reload the host.
This generator does not change user-wide settings or install dependencies for generated skills.

## Try it

Copy this prompt into the selected host, supplying the referenced files or your task material:

> ${trial}

${templateName === 'meeting-notes'
    ? 'Use only the Raw input section first. Then compare the response with Expected output and Acceptance checks in [the example](references/example.md). Wording may differ; supported facts and missing-information labels should agree.'
    : 'This is a starter. Add your actual task rules and an input/output example before relying on it for repeated work.'}

## Verification status

Run \`create-agent-skill validate <path-to-this-folder>\` from an installed CLI, or use the repository CLI.
Format validation checks local files only. It does not run an agent, execute scripts, install dependencies, or prove the skill works in a host.
Example behavior: not run. Host discovery and invocation: not verified.
`;
}

function planSkill(options, cwd = process.cwd()) {
  const name = options.name.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  if (!name) inputError('Use an English slug such as meeting-notes; use --title for a Chinese display title.');
  const templateName = options.template || 'basic';
  const target = options.target || 'generic';
  if (!Object.hasOwn(templates, templateName)) inputError('Unknown template. Choose basic or meeting-notes.');
  if (!Object.hasOwn(targets, target)) inputError('Unknown target. Choose generic, claude, cursor or codex.');
  const title = options.title || name.split('-').map((word) => word[0].toUpperCase() + word.slice(1)).join(' ');
  if (/[\r\n]/.test(title)) inputError('--title must be a single line.');
  const description = options.desc ?? templates[templateName].description ?? `Use when the user requests the ${name} workflow. Add task-specific inputs, output and rules before repeated use.`;
  const outDir = path.resolve(cwd, options.dir || path.join(targets[target].directory || '', name));
  const errors = metadataErrors({ name, description }, path.basename(outDir));
  if (errors.length) inputError(errors.join('\n'));
  const variables = { NAME: name, TITLE: title, DESCRIPTION: description,
    FRONTMATTER: YAML.stringify({ name, description }, { lineWidth: 0 }).trimEnd() };
  const sourceDirectory = path.join(templatesRoot, templateName);
  const files = [];
  function collect(directory) {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const sourcePath = path.join(directory, entry.name);
      if (entry.isDirectory()) collect(sourcePath);
      else if (entry.isFile()) files.push({ path: path.relative(sourceDirectory, sourcePath),
        content: entry.name.endsWith('.md') ? render(fs.readFileSync(sourcePath, 'utf8'), variables) : fs.readFileSync(sourcePath) });
      else throw new Error(`Template resources must be regular files: ${sourcePath}`);
    }
  }
  collect(sourceDirectory);
  const skillFile = files.find((file) => file.path === 'SKILL.md');
  if (!skillFile) throw new Error('Template has no SKILL.md.');
  const rendered = parseSkill(skillFile.content);
  const renderedErrors = metadataErrors(rendered.data, name);
  if (renderedErrors.length || !rendered.body.trim()) throw new Error(`Invalid template: ${renderedErrors.join(' ') || 'empty instructions'}`);
  files.push({ path: 'README.md', content: installGuide(name, title, target, templateName) });
  return { name, title, outDir, files, target, templateName };
}

function assertWritablePath(root, relative) {
  const pieces = relative.split(path.sep);
  let current = root;
  for (let index = -1; index < pieces.length; index++) {
    if (index >= 0) current = path.join(current, pieces[index]);
    let stat;
    try { stat = fs.lstatSync(current); } catch (error) { if (error.code === 'ENOENT') continue; throw error; }
    if (stat.isSymbolicLink()) throw new Error(`Refusing to overwrite a linked path: ${current}`);
    const isFile = index === pieces.length - 1;
    if (isFile ? !stat.isFile() : !stat.isDirectory()) throw new Error(`Unexpected file type: ${current}`);
  }
}

function writeSkill(plan, { force = false, dryRun = false } = {}) {
  for (const file of plan.files) assertWritablePath(plan.outDir, file.path);
  const exists = fs.existsSync(plan.outDir);
  if (dryRun) return { dryRun: true, exists, backup: null };
  if (exists && !force) throw new Error(`Refusing to overwrite existing folder: ${plan.outDir}\nPreview with --dry-run, or use --force to back up and replace generated files.`);
  const overwritten = plan.files.filter((file) => fs.existsSync(path.join(plan.outDir, file.path)));
  let backup = null;
  if (overwritten.length) {
    backup = fs.mkdtempSync(`${plan.outDir}.backup-`);
    for (const file of overwritten) {
      // .bak keeps backups from being discovered as a second live skill.
      const destination = path.join(backup, `${file.path}.bak`);
      fs.mkdirSync(path.dirname(destination), { recursive: true });
      fs.copyFileSync(path.join(plan.outDir, file.path), destination);
    }
  }
  for (const file of plan.files) {
    const destination = path.join(plan.outDir, file.path);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.writeFileSync(destination, file.content, { flag: force ? 'w' : 'wx' });
  }
  return { dryRun: false, exists, backup };
}

module.exports = { planSkill, writeSkill };
